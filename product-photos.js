function cleanName(name) {
  return String(name || "").normalize("NFKC")
    .replace(/\(青龍\)/g, "")
    .replace(/\s+/g, "")
    .replace(/^(新鮮|嚴選|特選|特級|有機|本土|本地|進口|台灣|臺灣)+/, "")
    .replace(/(?:[（(]?\d+(?:\.\d+)?(?:公斤|公克|台斤|斤|顆|條|把|包|份|g|kg)[）)]?)$/, "");
}
